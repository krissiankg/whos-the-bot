-- Transaction-isolated fixtures: no real provider requests or retained players.
begin;
set local role service_role;
do $$
#variable_conflict use_variable
declare a text:=encode(extensions.gen_random_bytes(32),'hex'); b text:=encode(extensions.gen_random_bytes(32),'hex');
  ip text:=encode(extensions.gen_random_bytes(32),'hex'); x jsonb; code text; room uuid; rid uuid;
  j game.bot_jobs%rowtype; n integer;
begin
  x:=public.lobby_command('create',jsonb_build_object('requestId',gen_random_uuid(),'language','fr'),a,ip);
  room:=(x#>>'{room,id}')::uuid;code:=x#>>'{room,code}';
  perform public.lobby_command('join',jsonb_build_object('code',code),b,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),b,ip);
  x:=public.lobby_command('start',jsonb_build_object('code',code,'practice',true,'_aiReady',true),a,ip);
  rid:=(x#>>'{round,id}')::uuid;
  assert not exists(select 1 from game.bot_jobs where round_id=rid),'no work before a human speaks';
  perform public.lobby_command('message',jsonb_build_object('code',code,'text','les crêpes au citron ça me tente','requestId',gen_random_uuid()),a,ip);
  perform game.advance_round(room);
  select * into j from game.bot_jobs where round_id=rid;
  update game.bot_jobs set status='sent',started_at=now() where id=j.id;
  assert public.bot_job_command(j.id,gen_random_uuid(),'fail','provider_auth') is null,'forged capability cannot fail a job';
  x:=public.bot_job_command(j.id,j.capability,'claim');
  assert x->>'language'='fr','trusted language preserved';
  perform public.bot_job_command(j.id,j.capability,'finish','je suis une IA');
  assert (select status='failed' and body is null and failure_code='output_filtered' from game.bot_jobs where id=j.id),'unsafe text discarded';
  assert (select phase='chat' from game.rounds where id=rid),'one failure does not cancel';
  assert public.bot_job_command(j.id,j.capability,'claim') is null,'claim cannot be replayed';
  perform public.bot_job_command(j.id,j.capability,'fail','provider_auth');
  assert (select phase='chat' from game.rounds where id=rid),'late duplicate fail cannot cancel';
  perform game.advance_round(room);
  assert (select count(*) from game.bot_jobs where round_id=rid)=1,'cooldown prevents immediate model retry';
  x:=public.lobby_command('state',jsonb_build_object('code',code),a,ip);
  assert x#>'{round,cancelReason}' is null and x#>'{round,reveal}' is null,'no failure or identity hints during chat';
  assert jsonb_array_length(x#>'{round,messages}')=1,'only the human opener is visible';
  assert x#>>'{round,messages,0,text}'='les crêpes au citron ça me tente','unsafe output never reaches players';
  insert into game.bot_jobs(round_id,status,started_at,created_at) values(rid,'sent',now(),now()+interval '1 second') returning * into j;
  perform public.bot_job_command(j.id,j.capability,'claim');
  perform public.bot_job_command(j.id,j.capability,'finish','les crepes et une balade, et vous ?');
  assert (select publish_at between now()+interval '2 seconds' and now()+interval '8 seconds' from game.bot_jobs where id=j.id),'typing delay retained';
  update game.bot_jobs set publish_at=now()-interval '1 second' where id=j.id;
  perform game.advance_round(room);
  assert (select status='posted' from game.bot_jobs where id=j.id),'valid later reply publishes';
  for n in 2..4 loop
    insert into game.bot_jobs(round_id,status,started_at,created_at) values(rid,'sent',now(),now()+make_interval(secs=>n)) returning * into j;
    perform public.bot_job_command(j.id,j.capability,'claim');
    perform public.bot_job_command(j.id,j.capability,'fail','provider_timeout');
    if n<4 then assert (select phase='chat' from game.rounds where id=rid),'isolated errors have bounded recovery'; end if;
  end loop;
  assert (select phase='cancelled' and cancelled_reason='ai_service' from game.rounds where id=rid),'three consecutive failures stop clearly';
  x:=public.lobby_command('state',jsonb_build_object('code',code),a,ip);
  assert x#>>'{round,cancelReason}'='ai_service','safe cancellation reason returned';
  assert x#>'{round,reveal}' is null and x#>'{round,result}' is null,'cancellation reveals no roles and awards no score';
  assert not exists(select 1 from game.round_scores where round_id=rid),'no score for interruption';
  update game.rounds set phase='chat',cancelled_reason=null,deadline=now()+interval '120 seconds' where id=rid;
  update game.rooms set phase='chat' where id=room;
  insert into game.bot_jobs(round_id,status,started_at) values(rid,'sent',now()) returning * into j;
  perform public.bot_job_command(j.id,j.capability,'claim');
  perform public.bot_job_command(j.id,j.capability,'fail','provider_auth');
  assert (select cancelled_reason='ai_configuration' from game.rounds where id=rid),'invalid authorization fails closed without retries';
  update game.rounds set phase='chat',cancelled_reason=null where id=rid;
  update game.rooms set phase='chat' where id=room;
  insert into game.bot_jobs(round_id,status,started_at) values(rid,'sent',now()) returning * into j;
  insert into game.rate_limits(bucket,hits,expires_at) values('ai-budget-reservations',200,now()+interval '24 hours') on conflict(bucket) do update set hits=200;
  assert public.bot_job_command(j.id,j.capability,'claim') is null,'no model request above budget';
  assert (select cancelled_reason='ai_budget' from game.rounds where id=rid),'budget limit clearly identified';
  -- Existing six-job maximum cannot be bypassed by failed jobs.
  update game.rounds set phase='chat',cancelled_reason=null,next_bot_at=now()-interval '1 second' where id=rid;
  update game.rooms set phase='chat' where id=room;
  n:=(select count(*) from game.bot_jobs where round_id=rid);
  perform game.advance_round(room);
  assert (select count(*) from game.bot_jobs where round_id=rid)=n,'six-attempt cap is unchanged';
  update game.rounds set pause_until=now()-interval '1 second' where id=rid;
  perform game.advance_round(room);
  assert (select cancelled_reason='players_disconnected' from game.rounds where id=rid),'presence timeout distinguished';
  assert not has_function_privilege('anon','game.fail_bot_job(uuid,text)','execute'),'private diagnostics not a public control endpoint';
  assert not has_function_privilege('authenticated','game.interrupt_round(uuid,text)','execute'),'browser cannot interrupt arbitrary rooms';
  assert not has_table_privilege('anon','game.bot_jobs','select'),'job metadata stays private';
end;
$$;
rollback;

