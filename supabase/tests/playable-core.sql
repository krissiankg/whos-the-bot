-- Run in the Supabase SQL editor / execute_sql. Everything rolls back, including
-- quotas and jobs. No model calls, messages, or test identities are retained.
begin;
set local role service_role;
do $$
#variable_conflict use_variable
declare
  a text:=encode(extensions.gen_random_bytes(32),'hex');
  b text:=encode(extensions.gen_random_bytes(32),'hex');
  outsider text:=encode(extensions.gen_random_bytes(32),'hex');
  ip text:=encode(extensions.gen_random_bytes(32),'hex');
  x jsonb; y jsonb; code text; room uuid; round_id uuid; pa uuid; pb uuid;
  sa uuid; sb uuid; bot uuid; message uuid; request uuid:=gen_random_uuid();
  j game.bot_jobs%rowtype; v_deadline timestamptz;
begin
  x:=public.lobby_command('create',jsonb_build_object('requestId',gen_random_uuid()),a,ip);
  code:=x#>>'{room,code}'; room:=(x#>>'{room,id}')::uuid; pa:=(x->>'meId')::uuid;
  if room is null then raise exception 'create failed %',x; end if;
  x:=public.lobby_command('start',jsonb_build_object('code',code,'_aiReady',true),a,ip);
  assert x->>'error'='NOT_READY','one human cannot start';
  x:=public.lobby_command('join',jsonb_build_object('code',code),b,ip); pb:=(x->>'meId')::uuid;
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),b,ip);
  x:=public.lobby_command('start',jsonb_build_object('code',code,'practice',true,'_aiReady',true),b,ip);
  assert x->>'error'='HOST_ONLY','guest cannot start';
  x:=public.lobby_command('start',jsonb_build_object('code',code,'_aiReady',true),a,ip);
  assert x->>'error'='PRACTICE_REQUIRED','two humans require explicit practice';
  x:=public.lobby_command('start',jsonb_build_object('code',code,'practice',true),a,ip);
  assert x->>'error'='AI_NOT_CONFIGURED','no pretend AI when key is absent';
  x:=public.lobby_command('start',jsonb_build_object('code',code,'practice',true,'_aiReady',true),a,ip);
  assert x#>>'{room,phase}'='chat','start chat';
  assert jsonb_array_length(x->'players')=3,'two humans plus exactly one bot';
  assert x#>'{round,reveal}' is null,'no premature reveal';
  assert x#>'{round,votes}' is null,'no premature votes';
  assert x#>>'{room,hostId}' is null,'no lobby host identity exposed during play';
  round_id:=(x#>>'{round,id}')::uuid; sa:=(x->>'meId')::uuid;
  assert sa<>pa,'round participant IDs must differ from lobby IDs';
  select id into sb from game.participants s where s.round_id=round_id and s.player_id=pb;
  select id into bot from game.participants s where s.round_id=round_id and s.player_id is null;
  assert (select count(*) from game.participants s where s.round_id=round_id and s.player_id is null)=1,'exactly one bot';
  assert (select extract(epoch from r.deadline-now()) from game.rounds r where r.id=round_id)=180,'180-second deadline';
  x:=public.lobby_command('join',jsonb_build_object('code',code),b,ip);
  assert (x->>'meId')::uuid=sb,'reconnect preserves round identity';
  x:=public.lobby_command('state',jsonb_build_object('code',code),outsider,ip);
  assert x->>'error'='NOT_A_MEMBER','room isolation';
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','   ','requestId',gen_random_uuid()),a,ip);
  assert x->>'error'='MESSAGE_REJECTED','empty rejected';
  assert not game.safe_message('putain'),'French filter';
  assert not game.safe_message('fuck off'),'English filter';
  assert not game.safe_message('https://example.com'),'links rejected';
  assert game.safe_message('Pancakes are underrated!'),'normal text accepted';
  assert not game.safe_bot_message('you caught me, the bot is me'),'bot role vocabulary rejected';
  assert not game.safe_bot_message('I am a human'),'false human claim rejected';
  assert game.safe_bot_message('i am a pancake fan lol'),'ordinary fictional opinions accepted';
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','Pancakes are underrated!','requestId',request),a,ip);
  assert x->>'error' is null,'send message';
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','Pancakes are underrated!','requestId',request),a,ip);
  assert jsonb_array_length(x#>'{round,messages}')=1,'idempotent message retry';
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','More pancakes','requestId',gen_random_uuid()),a,ip);
  assert x->>'error'='RATE_LIMITED','burst limit';
  select m.id into message from game.messages m where m.round_id=round_id;
  x:=public.lobby_command('report',jsonb_build_object('code',code,'messageId',message),b,ip);
  assert jsonb_array_length(x#>'{round,reportedIds}')=1,'report receipt';
  assert jsonb_array_length(x#>'{round,hostReportIds}')=0,'only host gets reports';
  x:=public.lobby_command('state',jsonb_build_object('code',code),a,ip);
  assert jsonb_array_length(x#>'{round,hostReportIds}')=1,'host sees reports';
  -- Claim is single-use, with a reserved generation budget and bounded context.
  select * into j from game.bot_jobs z where z.round_id=round_id;
  update game.bot_jobs set status='sent',started_at=now() where id=j.id;
  assert public.bot_job_command(j.id,gen_random_uuid(),'claim') is null,'forged capability rejected';
  x:=public.bot_job_command(j.id,j.capability,'claim');
  assert x->>'topic' is not null,'worker gets private context';
  assert public.bot_job_command(j.id,j.capability,'claim') is null,'duplicate claim rejected';
  perform public.bot_job_command(j.id,j.capability,'finish','i vote for pancakes. anyone bringing syrup?');
  assert (select publish_at between now()+interval '2 seconds' and now()+interval '8 seconds' from game.bot_jobs where id=j.id),'random typing delay';
  update game.bot_jobs set publish_at=now()-interval '1 second' where id=j.id;
  perform game.advance_round(room);
  perform game.advance_round(room);
  assert (select count(*) from game.messages m where m.round_id=round_id and participant_id=bot)=1,'bot published once';
  assert not exists(select 1 from game.bot_jobs z where z.round_id=round_id and z.status='queued'),'bot cooldown respected';
  -- Late chat triggers lazy advancement; new vote window anchored to deadline.
  update game.rounds set deadline=now()-interval '1 second' where id=round_id;
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','Too late','requestId',gen_random_uuid()),a,ip);
  assert x->>'error'='CHAT_CLOSED','late chat rejected';
  assert (select phase from game.rooms where id=room)='vote','lazy transition';
  select deadline into v_deadline from game.rounds where id=round_id;
  assert v_deadline=now()+interval '29 seconds','vote timer anchored, no reset';
  x:=public.lobby_command('vote',jsonb_build_object('code',code,'targetId',sa),a,ip);
  assert x->>'error'='INVALID_TARGET','no self vote';
  x:=public.lobby_command('vote',jsonb_build_object('code',code,'targetId',bot),a,ip);
  assert (x#>>'{round,myVote}')::uuid=bot,'own vote returned';
  assert x#>'{round,reveal}' is null,'votes still hidden';
  x:=public.lobby_command('vote',jsonb_build_object('code',code,'targetId',bot),a,ip);
  assert x->>'error' is null,'vote retry idempotent';
  x:=public.lobby_command('vote',jsonb_build_object('code',code,'targetId',sb),a,ip);
  assert x->>'error'='VOTE_LOCKED','cannot change final vote';
  x:=public.lobby_command('state',jsonb_build_object('code',code),b,ip);
  assert x#>>'{round,myVote}' is null,'other vote private';
  update game.rounds set deadline=now() where id=round_id;
  x:=public.lobby_command('vote',jsonb_build_object('code',code,'targetId',bot),b,ip);
  assert x->>'error'='VOTE_CLOSED','boundary vote rejected';
  x:=public.lobby_command('state',jsonb_build_object('code',code),a,ip);
  assert (x#>>'{round,reveal,botId}')::uuid=bot,'reveal identifies bot';
  assert jsonb_array_length(x#>'{round,reveal,votes}')=2,'only human ballots, includes abstention';
  assert (select count(*) from jsonb_array_elements(x#>'{round,reveal,votes}') v where v->>'targetId' is null)=1,'absent voter abstains';
  -- Presence pause, bounded reconnect, no prompt or identity leaks on cancel.
  update game.rounds set phase='chat',deadline=now()+interval '120 seconds' where id=round_id;
  update game.rooms set phase='chat' where id=room;
  update game.players set last_seen=now()-interval '30 seconds' where id=pb;
  perform game.advance_round(room);
  assert (select pause_until is not null from game.rounds where id=round_id),'pause below two';
  x:=public.lobby_command('message',jsonb_build_object('code',code,'text','Paused','requestId',gen_random_uuid()),a,ip);
  assert x->>'error'='CHAT_CLOSED','paused chat rejected';
  x:=public.lobby_command('state',jsonb_build_object('code',code),b,ip);
  assert x#>>'{round,pausedUntil}' is null,'reconnect resumes';
  update game.players set last_seen=now()-interval '50 seconds' where id=pa;
  perform game.elect_host(room);
  assert (select host_id=pb from game.rooms where id=room),'host disconnect transfers';
  x:=public.lobby_command('kick',jsonb_build_object('code',code,'playerId',bot),b,ip);
  assert x#>>'{round,phase}'='cancelled','bot kick cancels uniformly';
  assert x#>'{round,reveal}' is null,'cancel does not reveal bot';
  -- One filtered attempt is discarded without revealing roles or cancelling.
  update game.rounds set phase='chat',deadline=now()+interval '120 seconds' where id=round_id;
  update game.rooms set phase='chat' where id=room;
  update game.players set last_seen=now() where id=pa;
  insert into game.bot_jobs(round_id,status,started_at) values(round_id,'sent',now()) returning * into j;
  perform public.bot_job_command(j.id,j.capability,'claim');
  perform public.bot_job_command(j.id,j.capability,'finish','I am an AI');
  assert (select phase='chat' from game.rounds where id=round_id),'one rejected output does not cancel';
  assert (select status='failed' and failure_code='output_filtered' from game.bot_jobs where id=j.id),'identity-leaking output rejected';
  assert public.bot_job_command(j.id,j.capability,'claim') is null,'failed generation cannot be retried';
  -- Reserved global budget is enforced before contacting the provider.
  update game.rounds set phase='chat',deadline=now()+interval '120 seconds' where id=round_id;
  update game.rooms set phase='chat' where id=room;
  insert into game.bot_jobs(round_id,status,started_at) values(round_id,'sent',now()) returning * into j;
  insert into game.rate_limits(bucket,hits,expires_at) values('ai-budget-reservations',200,now()+interval '24 hours')
    on conflict(bucket) do update set hits=200;
  assert public.bot_job_command(j.id,j.capability,'claim') is null,'budget exhaustion rejects generation';
  assert (select phase='cancelled' from game.rounds where id=round_id),'budget exhaustion cancels without identity leak';
  -- Expired reconnect grace cannot resume an abandoned round.
  update game.rounds set phase='chat',pause_until=now()-interval '1 second',remaining_seconds=90 where id=round_id;
  update game.rooms set phase='chat' where id=room;
  perform game.advance_round(room);
  assert (select phase='cancelled' from game.rounds where id=round_id),'pause timeout cancels';
  assert not has_function_privilege('anon','public.bot_job_command(uuid,uuid,text,text)','EXECUTE'),'anonymous cannot claim bot';
  assert not has_function_privilege('authenticated','public.lobby_command(text,jsonb,text,text)','EXECUTE'),'browser cannot invoke gateway';
  -- 24-hour cascade also removes new participants, ballots, jobs and reports.
  update game.rooms set expires_at=now()-interval '1 second' where id=room;
  x:=public.lobby_command('state',jsonb_build_object('code',code),b,ip);
  assert x->>'error'='ROOM_NOT_FOUND','expired room denied before deletion';
  delete from game.rooms where id=room;
  assert not exists(select 1 from game.participants where game.participants.round_id=round_id),'participant cascade';
  assert not exists(select 1 from game.bot_jobs where game.bot_jobs.round_id=round_id),'job cascade';
  assert not exists(select 1 from game.ballots where game.ballots.round_id=round_id),'ballot cascade';
  -- Standard game path, with three humans and no practice acknowledgment.
  x:=public.lobby_command('create',jsonb_build_object('requestId',gen_random_uuid()),a,ip);
  code:=x#>>'{room,code}'; room:=(x#>>'{room,id}')::uuid;
  perform public.lobby_command('join',jsonb_build_object('code',code),b,ip);
  perform public.lobby_command('join',jsonb_build_object('code',code),outsider,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),b,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),outsider,ip);
  x:=public.lobby_command('start',jsonb_build_object('code',code,'_aiReady',true),a,ip);
  assert x#>>'{room,phase}'='chat','standard three-human game starts';
  assert x#>>'{round,practice}'='false','three-human game is not practice';
  assert jsonb_array_length(x->'players')=4,'three humans plus one bot';
  assert x#>'{round,reveal}' is null,'standard game hides bot';
  round_id:=(x#>>'{round,id}')::uuid;
  select s.id into sb from game.participants s join game.players p on p.id=s.player_id where s.round_id=round_id and p.session_hash=b;
  x:=public.lobby_command('kick',jsonb_build_object('code',code,'playerId',sb),a,ip);
  assert x#>>'{round,phase}'='cancelled','human kick also cancels';
  assert x#>'{round,reveal}' is null,'human kick also hides roles';
  x:=public.lobby_command('state',jsonb_build_object('code',code),b,ip);
  assert x->>'error'='KICKED','kicked participant loses access';
end;
$$;
rollback;
