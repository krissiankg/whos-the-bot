-- Disposable bilingual game tests; no provider calls survive the rollback.
begin;
set local role service_role;
do $$
declare a text:=encode(extensions.gen_random_bytes(32),'hex'); b text:=encode(extensions.gen_random_bytes(32),'hex');
  ip text:=encode(extensions.gen_random_bytes(32),'hex'); x jsonb; y jsonb; code text; room uuid; rid uuid; job uuid; cap uuid; request uuid:=gen_random_uuid();
begin
  x:=public.lobby_command('create',jsonb_build_object('requestId',request,'language','de'),a,ip);
  assert x->>'error'='INVALID_REQUEST','invalid creation language rejected';
  x:=public.lobby_command('create',jsonb_build_object('requestId',request,'language',null),a,ip);
  assert x->>'error'='INVALID_REQUEST','null language rejected';
  x:=public.lobby_command('create',jsonb_build_object('requestId',request,'language','fr'),a,ip);
  assert x#>>'{room,language}'='fr','French creation persisted';
  assert x#>>'{players,0,name}'='Joueur 1','French neutral waiting seats';
  code:=x#>>'{room,code}'; room:=(x#>>'{room,id}')::uuid;
  y:=public.lobby_command('create',jsonb_build_object('requestId',request,'language','en'),a,ip);
  assert x#>>'{room,id}'=y#>>'{room,id}' and y#>>'{room,language}'='fr','retry cannot silently change room language';
  y:=public.lobby_command('join',jsonb_build_object('code',code,'language','en'),b,ip);
  assert y#>>'{room,language}'='fr','joining does not change host choice';
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','en'),b,ip);
  assert y->>'error'='HOST_ONLY','guest cannot change language';
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','de'),a,ip);
  assert y->>'error'='INVALID_REQUEST','host cannot use unsupported language';
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language',null),a,ip);
  assert y->>'error'='INVALID_REQUEST','host null language rejected';
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),b,ip);
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','en'),a,ip);
  assert y#>>'{room,language}'='en','host can change language';
  assert not exists(select 1 from jsonb_array_elements(y->'players') p where (p->>'ready')::boolean),'changing language clears readiness';
  y:=public.lobby_command('state',jsonb_build_object('code',code),b,ip);
  assert y#>>'{room,language}'='en','language synchronized for guest';
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','fr'),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),a,ip);
  perform public.lobby_command('ready',jsonb_build_object('code',code,'ready',true),b,ip);
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','fr'),a,ip);
  assert not exists(select 1 from jsonb_array_elements(y->'players') p where not (p->>'ready')::boolean),'same language preserves readiness';
  x:=public.lobby_command('start',jsonb_build_object('code',code,'practice',true,'_aiReady',true),a,ip);
  assert x#>>'{room,phase}'='chat','French round started';
  assert x#>>'{round,topic}' in ('Décris ton week-end idéal.','Quelle invention inoffensive devrait exister ?','Quel mélange alimentaire insolite aimes-tu ?','Quel lieu imaginaire aimerais-tu visiter ?','Quel petit détail embellit ta journée ?'),'French topics';
  assert x#>>'{players,0,name}' in ('Renard orange','Chat lilas','Grenouille menthe','Lapin rose','Ours bleu','Oiseau doré','Hibou azur'),'French round aliases';
  assert x#>'{round,reveal}' is null,'no bot identity leaked';
  rid:=(x#>>'{round,id}')::uuid;
  y:=public.lobby_command('language',jsonb_build_object('code',code,'language','en'),a,ip);
  assert y->>'error'='ROUND_IN_PROGRESS','language locked during play';
  assert not exists(select 1 from game.bot_jobs where round_id=rid),'no work before the first human';
  perform public.lobby_command('message',jsonb_build_object('code',code,'text','les crêpes au citron ça me tente','requestId',gen_random_uuid()),a,ip);
  perform game.advance_round(room);
  update game.bot_jobs set status='sent',started_at=now() where round_id=rid and status='queued' returning id,capability into job,cap;
  assert job is not null,'human message enabled one pending bot job';
  y:=public.bot_job_command(job,cap,'claim');
  assert y->>'language'='fr','trusted bot context carries room language';
  assert y->>'topic'=x#>>'{round,topic}','bot sees same French topic';
  assert y->>'nickname' in ('Renard orange','Chat lilas','Grenouille menthe','Lapin rose','Ours bleu','Oiseau doré','Hibou azur'),'bot nickname matches French roster';
  assert game.safe_message('Les crêpes au citron, c’est trop bon !'),'French accents accepted';
  assert not game.safe_message('putain'),'French basic profanity blocked';
  assert not game.safe_bot_message('Je suis une intelligence artificielle'),'French identity disclosure blocked';
  assert not game.safe_bot_message('je suis un humain'),'false French human claim blocked';
  assert game.safe_bot_message('les crêpes au citron c’est sous-coté mdr'),'normal French bot opinion accepted';
  x:=public.lobby_command('create',jsonb_build_object('requestId',gen_random_uuid()),b,ip);
  assert x#>>'{room,language}'='en','legacy clients default to English';
  assert game.localized_topic('Describe your perfect weekend.','en')='Describe your perfect weekend.','English topic preserved';
  assert not has_function_privilege('anon','public.lobby_command(text,jsonb,text,text)','execute'),'anon still denied';
  assert not has_function_privilege('authenticated','public.bot_job_command(uuid,uuid,text,text)','execute'),'authenticated still denied';
end;
$$;
rollback;
