-- Actual server-role auth, Vault encryption and independent key persistence.
-- Entire transaction rolls back. Never consumes the owner's setup link.
begin;
set local role service_role;
do $$
declare bridge text:=repeat('e',64); setup text:=repeat('d',64); session text:=repeat('c',64); ip text:=repeat('b',64);
  result jsonb; nvidia uuid; openai uuid; secret text; password text:='unit-test-owner-password';
begin
  update game.admin_control set bridge_hash=bridge,setup_hash=setup,setup_expires_at=now()+interval '1 hour',password_hash=null,active_provider='environment' where singleton;
  result:=public.admin_command(repeat('f',64),session,'status','{}',ip);
  assert result->>'error'='ADMIN_FORBIDDEN','wrong bridge rejected';
  result:=public.admin_command(bridge,session,'status','{}',ip);
  assert result->>'error'='ADMIN_UNAUTHORIZED','session required';
  result:=public.admin_command(bridge,session,'setup',jsonb_build_object('password',password,'setupHash',repeat('f',64)),ip);
  assert result->>'error'='ADMIN_SETUP_REJECTED','setup cannot be claimed without secret link';
  result:=public.admin_command(bridge,session,'setup',jsonb_build_object('password',password,'setupHash',setup),ip);
  assert result->>'initialized'='true','owner initialized';
  assert (select setup_hash is null from game.admin_control),'setup link consumed';
  assert (select password_hash<>password from game.admin_control),'password hashed';
  assert result::text not like '%'||password||'%','password never returned';
  result:=public.admin_command(bridge,repeat('a',64),'setup',jsonb_build_object('password',password,'setupHash',setup),ip);
  assert result->>'error'='ADMIN_SETUP_REJECTED','cannot initialize twice';
  result:=public.admin_command(bridge,session,'save',jsonb_build_object('provider','nvidia','apiKey','test-only-nvidia-secret-12345'),ip);
  assert result->>'error' is null,'save NVIDIA';
  assert result::text not like '%test-only-nvidia-secret%','saved key not returned';
  select secret_id into nvidia from game.provider_keys where provider='nvidia';
  select s.secret into secret from vault.secrets s where id=nvidia;
  assert secret<>'test-only-nvidia-secret-12345','NVIDIA encrypted at rest';
  result:=public.admin_command(bridge,session,'save',jsonb_build_object('provider','openai','apiKey','test-only-openai-secret-12345'),ip);
  assert result->>'error' is null,'save OpenAI';
  select secret_id into openai from game.provider_keys where provider='openai';
  assert nvidia<>openai,'separate Vault entries';
  assert (select decrypted_secret='test-only-nvidia-secret-12345' from vault.decrypted_secrets where id=nvidia),'saving OpenAI retains NVIDIA';
  perform public.admin_command(bridge,session,'activate','{"provider":"nvidia"}',ip);
  result:=public.provider_runtime();
  assert result->>'provider'='nvidia','runtime follows selected provider';
  assert result->>'apiKey'='test-only-nvidia-secret-12345','internal runtime can decrypt selected key';
  perform public.admin_command(bridge,session,'activate','{"provider":"openai"}',ip);
  assert public.provider_runtime()->>'apiKey'='test-only-openai-secret-12345','switch to stored OpenAI';
  assert (select decrypted_secret='test-only-nvidia-secret-12345' from vault.decrypted_secrets where id=nvidia),'switching retains other key';
  perform public.admin_command(bridge,session,'save','{"provider":"nvidia","apiKey":""}',ip);
  assert (select secret_id=nvidia from game.provider_keys where provider='nvidia'),'blank key preserves existing key';
  perform public.admin_command(bridge,session,'save','{"provider":"nvidia","apiKey":"test-only-nvidia-replacement"}',ip);
  assert (select decrypted_secret='test-only-nvidia-replacement' from vault.decrypted_secrets where id=nvidia),'replacement updates same encrypted entry';
  assert (select decrypted_secret='test-only-openai-secret-12345' from vault.decrypted_secrets where id=openai),'replacement retains OpenAI';
  result:=public.admin_command(bridge,session,'save','{"provider":"openai","model":"expensive-model"}',ip);
  assert result->>'error'='INVALID_REQUEST','unbudgeted model denied';
  perform public.admin_command(bridge,session,'activate','{"provider":"disabled"}',ip);
  assert public.provider_runtime()->>'provider' is null,'disable prevents runtime fallback';
  assert (select count(*)=2 from game.provider_keys where secret_id is not null),'disable retains both keys';
  result:=public.admin_command(bridge,repeat('f',64),'login',jsonb_build_object('password','wrong-long-password'),ip);
  assert result->>'error'='ADMIN_BAD_PASSWORD','wrong password denied';
  result:=public.admin_command(bridge,repeat('f',64),'login',jsonb_build_object('password',password),ip);
  assert result->>'error' is null,'correct password logs in';
  assert (select expires_at=now()+interval '8 hours' from game.admin_sessions where token_hash=repeat('f',64)),'session expires after eight hours';
  perform public.admin_command(bridge,session,'logout','{}',ip);
  result:=public.admin_command(bridge,session,'status','{}',ip);
  assert result->>'error'='ADMIN_UNAUTHORIZED','logout revokes session';
  assert not has_function_privilege('anon','public.provider_runtime(text)','EXECUTE'),'browser cannot decrypt runtime';
  assert not has_function_privilege('anon','public.admin_command(text,text,text,jsonb,text)','EXECUTE'),'browser cannot invoke admin RPC';
end;
$$;
rollback;
